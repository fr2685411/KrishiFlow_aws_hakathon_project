package com.example.data.advisory

import com.squareup.moshi.Json
import com.squareup.moshi.JsonClass

/**
 * Recommended strategy: whether to sell now, store, or stagger release
 */
enum class MarketTimingDecision(val label: String, val hindiLabel: String, val colorHex: Long) {
    SELL_IMMEDIATELY("Sell Immediately (तुरंत बेचें)", "मंडियों में पीक भाव - जल्द बिक्री कर मुनाफा सुरक्षित करें", 0xFF15803D),
    STORE_FOR_LATER("Hold & Store (भंडारण करें)", "भाव बढ़ने की संभावना - फसल सुरक्षित स्टोर करें", 0xFF0284C7),
    STAGGERED_SALE("Staggered Split Sale (किस्तों में बेचें)", "50% तुरंत बेचें, 50% उच्च भाव हेतु स्टोर करें", 0xFFD97706),
    URGENT_WEATHER_CLEARANCE("Emergency Weather Clearance (मौसम जोखिम)", "बारिश या नमी से पहले तुरंत निकासी करें", 0xFFDC2626)
}

/**
 * Input for the Gemini Harvest & Weather Profit Maximizer
 */
data class GeminiSellOrStoreInput(
    val cropName: String,
    val variety: String,
    val quantityKg: Double,
    val currentAskingPricePerKg: Double,
    val mandiRatePerKg: Double,
    val currentMandiTrend: String, // "UP", "DOWN", "STABLE"
    val daysSinceHarvest: Int,
    val estimatedFreshnessDaysRemaining: Int,
    val storageCondition: String,
    // Live Weather Metrics
    val locationName: String,
    val currentTemp: Double,
    val humidityPercent: Int,
    val rainProbabilityToday: Int,
    val upcoming3DayRainSumMm: Double,
    val weatherCondition: String
)

/**
 * Output recommendation generated by Gemini API
 */
@JsonClass(generateAdapter = true)
data class GeminiSellOrStoreRecommendation(
    @Json(name = "cropName") val cropName: String,
    @Json(name = "decision") val decision: String, // SELL_IMMEDIATELY, STORE_FOR_LATER, STAGGERED_SALE, URGENT_WEATHER_CLEARANCE
    @Json(name = "headline") val headline: String,
    @Json(name = "primaryReasoning") val primaryReasoning: String,
    @Json(name = "recommendedActionWindow") val recommendedActionWindow: String, // e.g. "Next 24 to 36 Hours"
    @Json(name = "projectedNetProfitPerKg") val projectedNetProfitPerKg: Double,
    @Json(name = "potentialProfitGainPercent") val potentialProfitGainPercent: Double,
    @Json(name = "weatherImpactAnalysis") val weatherImpactAnalysis: String,
    @Json(name = "storageRiskLevel") val storageRiskLevel: String, // "LOW", "MODERATE", "CRITICAL"
    @Json(name = "storageGuidelines") val storageGuidelines: String,
    @Json(name = "targetBuyersOrMarkets") val targetBuyersOrMarkets: String,
    @Json(name = "isLiveAiGenerated") val isLiveAiGenerated: Boolean = true
) {
    val timingDecision: MarketTimingDecision
        get() = try {
            MarketTimingDecision.valueOf(decision)
        } catch (_: Exception) {
            when {
                decision.contains("SELL", ignoreCase = true) -> MarketTimingDecision.SELL_IMMEDIATELY
                decision.contains("STORE", ignoreCase = true) -> MarketTimingDecision.STORE_FOR_LATER
                decision.contains("STAGGER", ignoreCase = true) -> MarketTimingDecision.STAGGERED_SALE
                else -> MarketTimingDecision.SELL_IMMEDIATELY
            }
        }
}
